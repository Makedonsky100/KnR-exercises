#include <stdio.h> //включение информации о библитотеке ввода-вывода
int main (){ //определение функции main, которая вернет целое число.
	int c; //объявление переменной целочисленного типа
	c = getchar() != EOF; /*присваивание переменной значения,
						которое считала функция getchar, не равное значению конца файла
	
					    Сначала выполняется getchar(), программа ждет ввода символа с клавиатуры.
						Затем выполняется сравнение: (введенный_символ) != EOF. Программа спрашивает, не равен ли символ 
	                    концу файла, а затем присваивает переменной введенное значение
	                    */
	printf("%d", c); //вызов функции форматированного вывода. выводим целое число
	return 0; //сообщаем ОС обл успешном завершении программы. Код возврата - 0.
}
